#!/usr/bin/env python3
"""Assemble Kira's offline HTML from its authored source files."""

from argparse import ArgumentParser
from hashlib import sha256
import json
import re
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src"
OUTPUT = ROOT / "Kira.html"
SDK_OUTPUT = ROOT / "KiraSDK.js"

MODEL = (
    "canonical.js",
    "unicode-data.js",
    "unicode.js",
    "artifact-data.js",
    "artifact-checker.js",
    "query-types.js",
    "query-checker.js",
    "engine.js",
    "parser.js",
    "wordnet-topics.js",
    "conversation.js",
    "dialogue-assets.js",
    "theme-packs.js",
    "themes.js",
    "field.js",
    "variation.js",
    "interaction.js",
    "creative.js",
    "realization.js",
    "dialogue.js",
)
BROWSER = ("persistence.js", "presenter.js", "view.js")
NARRATIVE = ("compiler.js", "world.js")


def read_parts(directory: str, names: tuple[str, ...]) -> str:
    return "".join((SOURCE / directory / name).read_text(encoding="utf-8") for name in names)


def pin_metadata() -> None:
    """Rewrite APP_META's hashes after the model or artifact changed."""
    model = read_parts("model", MODEL)
    body, marker, metadata = model.partition("Kira.APP_META=")
    artifact = re.search(r'"hash":"([0-9a-f]{64})"\};\s*$', (SOURCE / "model" / "artifact-data.js").read_text(encoding="utf-8"))
    if not marker or not artifact:
        raise ValueError("Could not find APP_META or the artifact hash")
    meta = json.loads(metadata.split(";", 1)[0])
    meta["artifactHash"] = artifact.group(1)
    meta["modelHash"] = sha256(body.encode("utf-8")).hexdigest()
    target = SOURCE / "model" / "dialogue.js"
    text = target.read_text(encoding="utf-8")
    head, _, rest = text.partition("Kira.APP_META=")
    tail = rest.partition(";")[2]
    target.write_text(head + "Kira.APP_META=" + json.dumps(meta, separators=(",", ":")) + ";" + tail, encoding="utf-8")
    print(f"Pinned artifactHash {meta['artifactHash'][:12]}… and modelHash {meta['modelHash'][:12]}….")


def build() -> str:
    model = read_parts("model", MODEL)
    model_body, marker, metadata = model.partition("Kira.APP_META=")
    if not marker or model.count(marker) != 1:
        raise ValueError("Expected one Kira.APP_META declaration in the model")
    expected_hash = sha256(model_body.encode("utf-8")).hexdigest()
    if json.loads(metadata.split(";", 1)[0])["modelHash"] != expected_hash:
        raise ValueError(f"Model changed; update APP_META.modelHash to {expected_hash} and the release version")
    browser = read_parts("browser", BROWSER)
    worker = model + (SOURCE / "worker-entry.js").read_text(encoding="utf-8")
    style = (SOURCE / "style.css").read_text(encoding="utf-8")
    html = (SOURCE / "shell.html").read_text(encoding="utf-8")

    for marker, value in (
        ("{{KIRA_STYLE}}", style),
        ("{{KIRA_MODEL}}", model),
        ("{{KIRA_WORKER}}", worker),
        ("{{KIRA_BROWSER}}", browser),
    ):
        if html.count(marker) != 1:
            raise ValueError(f"Expected exactly one {marker} in src/shell.html")
        html = html.replace(marker, value)

    return html


def build_sdk() -> str:
    model = read_parts("model", MODEL)
    narrative = read_parts("narrative", NARRATIVE)
    sdk_hash = sha256((model + narrative).encode("utf-8")).hexdigest()
    metadata = json.dumps({"version": "0.3.0", "sdkHash": sdk_hash}, separators=(",", ":"))
    # A private global object lets the unchanged browser model run in CommonJS
    # without leaking Kira onto Node's global scope.
    return (
        "// Generated by tools/build.py. Apache-2.0; see LICENSE.\n"
        "(function(root,factory){\n"
        "  if(typeof module==='object'&&module.exports)module.exports=factory();\n"
        "  else root.Kira=factory();\n"
        "})(globalThis,function(){\n'use strict';\n"
        "const Kira={};const globalThis={Kira};\n"
        + model + narrative
        + "Kira.NARRATIVE_META=" + metadata + ";\nreturn Kira;\n});\n"
    )


def main() -> int:
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--pin", action="store_true", help="re-pin APP_META hashes to the current model, then build")
    parser.add_argument("--check", action="store_true", help="fail if generated HTML or SDK differs from source")
    args = parser.parse_args()
    if args.pin:
        pin_metadata()
    outputs = ((OUTPUT, build().encode("utf-8")), (SDK_OUTPUT, build_sdk().encode("utf-8")))
    for output, data in outputs:
        if args.check:
            if not output.exists() or output.read_bytes() != data:
                print(f"{output.name} is out of date; run python3 tools/build.py", file=sys.stderr)
                return 1
            print(f"{output.name} matches the modular source.")
        else:
            output.write_bytes(data)
            print(f"Built {output.name} ({output.stat().st_size:,} bytes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
